  /* ---- events ------------------------------------------------------------------------------ */
  function reset() {
    var wasEdit = !!edit;
    clearDraft(); edit = null; state = { title: '', category: AN.CATEGORIES[0], description: '', body: '' }; figures = []; cover = 0; tab = 'write'; busy = false;
    if (wasEdit) loadDraft();                                   // after an edit, «Νέα ανακοίνωση» finds the draft it left
  }
  function submit() {
    note('', false);
    try { plan(); } catch (e) { note(explain({ code: 'semfe/' + e.code })); $('[data-note]').className = 'ed-note form-error'; return false; }
    var a = $('[data-actions]'); a.setAttribute('data-confirm', '1'); paintActions();
    var y = $('[data-yes]'); if (y) y.focus();
    return true;
  }
  function publish() {
    var a = $('[data-actions]'); a.removeAttribute('data-confirm');
    busy = true; paintActions();
    var payload = { action: edit ? 'update' : 'publish', title: state.title, category: state.category, description: state.description, body: bodyWithAlts(), cover: cover || 0,
      figures: figures.map(function (f) { return f.existing ? { existing: f.existing, size: f.size } : { data: f.base64, size: f.size }; }) };
    if (edit) { payload.file = edit.file; payload.sha = edit.sha; }
    A.callFunction('publishAnnouncement', payload).then(function (res) {
      busy = false; reset(); done(res);
    }, function (e) {
      busy = false; paintActions();
      var c = String((e && e.code) || '').replace(/^semfe\//, '');
      var n = $('[data-note]'); if (n) { n.textContent = edit && c === 'bad-request' ? CODES['edit-not-deployed'] : explain(e); n.className = 'ed-note form-error'; }
      var sb = $('[data-send]'); if (sb) sb.focus();
    });
  }
  function checkReady() {
    ready = null;
    A.callFunction('publishAnnouncement', { action: 'status' }).then(function (r) { ready = !!(r && r.ready); }, function (e) {
      ready = e && e.code === 'semfe/publishAnnouncement-unreachable' ? 'unreachable' : false;
    }).then(function () { if (open && !busy && box.querySelector('[data-form]')) refreshStatus(); });
  }
  function refreshStatus() {
    var panel = box.querySelector('.ed'); if (!panel) return;
    var old = panel.querySelector('.notice.warn, .ed > p.muted'); var fresh = document.createElement('div'); fresh.innerHTML = statusLine();
    if (old) old.parentNode.removeChild(old);
    if (fresh.firstChild) panel.insertBefore(fresh.firstChild, panel.querySelector('form'));
    var b = box.querySelector('[data-send]'); if (b) b.disabled = ready !== true;
  }

  function selectTab(name, focus) {
    tab = name;
    Array.prototype.forEach.call(box.querySelectorAll('[data-tab]'), function (x) {
      var on = x.getAttribute('data-tab') === name;
      x.setAttribute('aria-selected', String(on)); x.tabIndex = on ? 0 : -1;
      if (on && focus) x.focus();
    });
    $('#ed-pane-write').hidden = name !== 'write'; $('#ed-pane-preview').hidden = name !== 'preview';
    if (name === 'preview') preview(); else if (!focus) ta().focus();
  }

  box.addEventListener('input', function (e) {
    var t = e.target;
    if (t.hasAttribute('data-title')) state.title = t.value;
    else if (t.hasAttribute('data-desc')) state.description = t.value;
    else if (t.hasAttribute('data-body')) { state.body = t.value; paintCount(); }
    else if (t.hasAttribute('data-alt')) figures[+t.getAttribute('data-alt')].alt = t.value;
    else return;
    saveDraft(); previewSoon();
  });
  box.addEventListener('change', function (e) {
    var t = e.target;
    if (t.name === 'ed-cat') { state.category = t.value; saveDraft(); paintActions(); previewSoon(); }
    else if (t.hasAttribute('data-size')) { figures[+t.getAttribute('data-size')].size = t.value; previewSoon(); }
    else if (t.hasAttribute('data-cover')) { cover = +t.getAttribute('data-cover'); paintFigures(); }
    else if (t.hasAttribute('data-file')) { addFiles(t.files); t.value = ''; }
  });
  box.addEventListener('click', function (e) {
    var b = e.target.closest ? e.target.closest('button, a') : null;
    if (!b) return;
    if (b.hasAttribute('data-tool')) { e.preventDefault(); ACTIONS[b.getAttribute('data-tool')](); }
    else if (b.hasAttribute('data-tips')) { tips = !tips; var tb = $('[data-tipsbox]'); tb.hidden = !tips; b.setAttribute('aria-expanded', String(tips)); b.textContent = tipsLabel(); }
    else if (b.hasAttribute('data-tab')) selectTab(b.getAttribute('data-tab'), false);
    else if (b.hasAttribute('data-put')) insertMarker(+b.getAttribute('data-put') + 1);
    else if (b.hasAttribute('data-del')) removeFigure(+b.getAttribute('data-del'));
    else if (b.hasAttribute('data-yes')) publish();
    else if (b.hasAttribute('data-del-yes')) confirmDelete();
    else if (b.hasAttribute('data-delete-ask')) { if (busy) return; $('[data-actions]').setAttribute('data-confirm', 'delete'); paintActions(); var dy = $('[data-del-yes]'); if (dy) dy.focus(); }
    else if (b.hasAttribute('data-no')) { $('[data-actions]').removeAttribute('data-confirm'); paintActions(); var sb = $('[data-send]'); if (sb) sb.focus(); }
    else if (b.hasAttribute('data-cancel') || b.hasAttribute('data-close')) { if (busy) return; leaveEdit(); doomed = null; open = false; stopWatch(); paint(); bar.focus(); }
    else if (b.hasAttribute('data-new')) { if (busy) return; leaveEdit(); doomed = null; stopWatch(); open = true; paint(); checkReady(); var ti = $('[data-title]'); if (ti) ti.focus(); }
    else if (b.hasAttribute('data-edit-file')) startEdit(b.getAttribute('data-edit-file'));
    else if (b.hasAttribute('data-delete-file')) startDelete(b.getAttribute('data-delete-file'));
  });
  box.addEventListener('submit', function (e) { e.preventDefault(); if (!busy) submit(); });
  box.addEventListener('keydown', function (e) {
    var t = e.target;
    if (t.hasAttribute && t.hasAttribute('data-tab') && /^(ArrowLeft|ArrowRight|Home|End)$/.test(e.key)) {      // the two tabs: arrows, Home and End move between them
      e.preventDefault();
      selectTab(e.key === 'ArrowLeft' || e.key === 'Home' ? 'write' : 'preview', true);
      return;
    }
    if (!t.hasAttribute || !t.hasAttribute('data-body') || !(e.ctrlKey || e.metaKey)) return;
    var k = String(e.key).toLowerCase();
    if (k === 'b') { e.preventDefault(); ACTIONS.bold(); } else if (k === 'i') { e.preventDefault(); ACTIONS.italic(); } else if (k === 'k') { e.preventDefault(); ACTIONS.link(); }
  });
  box.addEventListener('paste', function (e) {
    var items = (e.clipboardData && e.clipboardData.files) || [];
    if (items.length && /^image\//.test(items[0].type || '')) { e.preventDefault(); addFiles(items); }
  });
  ['dragover', 'dragleave', 'drop'].forEach(function (name) {
    box.addEventListener(name, function (e) {
      var z = e.target.closest ? e.target.closest('[data-drop]') : null;
      if (!z) return;
      e.preventDefault();
      z.classList.toggle('over', name === 'dragover');
      if (name === 'drop' && e.dataTransfer) addFiles(e.dataTransfer.files);
    });
  });
  /* back from an edit to the draft of a new announcement (kept on this device all along) */
  function leaveEdit() {
    if (!edit && !figures.some(function (f) { return f.existing; })) return;
    edit = null; state = { title: '', category: AN.CATEGORIES[0], description: '', body: '' }; figures = []; cover = 0; tab = 'write'; loadDraft();
  }
  bar.addEventListener('click', function () {
    if (!user || busy) return;                                  // not while an announcement is being sent: it would hide the answer
    doomed = null;
    if (edit) { leaveEdit(); open = true; paint(); checkReady(); var t1 = $('[data-title]'); if (t1) t1.focus(); return; }   // «Νέα ανακοίνωση» while editing: a new one
    open = !open;
    if (open) { if (!state.title && !state.body) loadDraft(); paint(); checkReady(); var ti = $('[data-title]'); if (ti) ti.focus(); } else { paint(); }
  });

  /* ---- who is here ------------------------------------------------------------------------ */
  A.onChange(function (u) {
    var admin = !!(u && A.isAdmin(u));
    if (admin && (!user || user.uid !== u.uid)) {
      var switched = !!user;
      user = u; edit = null; state = { title: '', category: AN.CATEGORIES[0], description: '', body: '' }; figures = []; cover = 0; tab = 'write'; loadDraft();
      if (switched && open && !busy) { paint(); checkReady(); }        // another admin signed in while the box was open: show THEIR draft, not the last one's
    }
    if (!admin) { user = null; open = false; edit = null; doomed = null; stopWatch(); box.innerHTML = ''; box.hidden = true; }
    host.hidden = !admin;
    if (admin && pendingEdit && !busy && !edit) {                       // blog/?edit=FILE: the «Επεξεργασία» of an announcement's own page
      var toEdit = pendingEdit; pendingEdit = null;
      startEdit(toEdit, true);
      if (host.scrollIntoView) host.scrollIntoView({ block: 'start' });
    }
    if (admin && pendingDelete && !busy) {                              // blog/?delete=FILE: its «Διαγραφή»; nothing goes before the question is answered
      var toDelete = pendingDelete; pendingDelete = null;
      startDelete(toDelete, true);
      if (host.scrollIntoView) host.scrollIntoView({ block: 'start' });
    }
  }, { passive: true });         // a visitor who never signed in must not make this page load the sign-in library
