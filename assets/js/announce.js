  function shrink(file) {
    return new Promise(function (resolve, reject) {
      if (!/^image\//.test(file.type || '')) return reject({ code: 'semfe/figure-bad' });
      if (file.size > 25 * 1024 * 1024) return reject({ code: 'semfe/file-too-big' });
      var rd = new FileReader();
      rd.onerror = function () { reject({ code: 'semfe/figure-bad' }); };
      rd.onload = function () {
        var img = new Image();
        img.onerror = function () { reject({ code: 'semfe/figure-bad' }); };
        img.onload = function () {
          var W = img.naturalWidth || 1, H = img.naturalHeight || 1, scale = Math.min(1, MAX_SIDE / Math.max(W, H)), quality = 0.86, url = '', c, g, w, h;
          for (var round = 0; round < 14; round++) {
            w = Math.max(1, Math.round(W * scale)); h = Math.max(1, Math.round(H * scale));
            c = document.createElement('canvas'); c.width = w; c.height = h;
            g = c.getContext('2d'); g.fillStyle = '#fff'; g.fillRect(0, 0, w, h);       // transparent areas become white, not black
            g.drawImage(img, 0, 0, w, h);
            url = c.toDataURL('image/jpeg', quality);
            if (Math.floor((url.length - 23) * 3 / 4) <= FIGURE_BYTES) break;
            if (quality > 0.6) quality -= 0.1; else scale *= 0.8;
          }
          var bytes = Math.floor((url.length - 23) * 3 / 4);
          if (!/^data:image\/jpeg;base64,/.test(url) || bytes > FIGURE_BYTES) return reject({ code: 'semfe/figure-too-big' });
          resolve({ dataUrl: url, base64: url.slice(23), bytes: bytes, w: w, h: h });
        };
        img.src = rd.result;
      };
      rd.readAsDataURL(file);
    });
  }
